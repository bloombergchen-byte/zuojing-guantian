'use strict';
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const { chromium } = require('playwright');
const extension = path.resolve(__dirname, '../extension');
const genericImage = fs.readFileSync(path.join(extension, 'assets/site-icons/simple-lie.png'));
const personalRequests = new Set();
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width"><link rel="stylesheet" href="style.css"><link rel="stylesheet" href="action-picker.css"></head><body><div id="sky-edge-collage"><section class="sheet-dialog"><div id="picker"></div></section></div><script src="site-icons.js"></script><script src="action-library.js"></script></body></html>`;
const mime = { '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.svg': 'image/svg+xml' };
const server = http.createServer((request, response) => {
  const pathname = new URL(request.url, 'http://127.0.0.1').pathname;
  if (pathname === '/') return response.writeHead(200, { 'Content-Type': 'text/html' }).end(html);
  if (/^\/assets\/site-icons\/personal\/(?:rk-test-\d+\.png|target\.ico)$/.test(pathname)) { personalRequests.add(pathname); return response.writeHead(200, { 'Content-Type': 'image/png' }).end(genericImage); }
  const file = path.resolve(extension, '.' + pathname);
  if (!file.startsWith(extension + path.sep)) return response.writeHead(403).end();
  fs.readFile(file, (error, data) => error ? response.writeHead(404).end() : response.writeHead(200, { 'Content-Type': mime[path.extname(file)] || 'application/octet-stream' }).end(data));
});
let browser;
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 440, height: 650 }, reducedMotion: 'reduce' });
  const fingerprint = crypto.createHash('sha256').update('https://synthetic-target.example/', 'utf8').digest('hex');
  await context.addInitScript(fingerprint => {
    window.SkyPersonalIcons = Object.fromEntries(Array.from({ length: 64 }, (_, i) => ['site-' + i, { image: 'rk-test-' + i + '.png', pose: ['lie', 'lean', 'hug'][i % 3], box: [12, 41, 76, 45], fingerprint: 'a'.repeat(64) }]));
    window.SkyPersonalIcons.target = { image: 'rk-test-0.png', pose: 'lie', box: [12, 41, 76, 45], fingerprint, logo: 'target.ico', plate: 'dark' };
  }, fingerprint);
  const page = await context.newPage(), errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:') && !request.url().startsWith('data:')) external.push(request.url()); });
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  await page.evaluate(() => {
    window.selectedIds = [];
    const sites = Array.from({ length: 64 }, (_, i) => ({ id: 'site-' + i, name: '合成音乐 ' + i, url: 'https://synthetic-' + i + '.example/', group: 'guitar' }));
    window.picker = SkyActions.mount(document.querySelector('#picker'), { site: { name: '音乐', url: 'https://youtube.com/watch', group: 'guitar' }, sites, selected: 'simple-lie.png', onSelect: id => window.selectedIds.push(id) });
  });
  const choices = page.locator('.sky-action-choice');
  assert.equal(await choices.count(), 4, 'only a few recommendations are initially displayed');
  assert.deepEqual(await page.evaluate(() => window.selectedIds), [], 'mount does not select implicitly');
  assert.equal(await choices.first().getAttribute('type'), 'button');
  const choiceStyle = await choices.first().evaluate(node => ({ width: node.getBoundingClientRect().width, margin: getComputedStyle(node).marginLeft, padding: getComputedStyle(node).paddingLeft }));
  assert.deepEqual(choiceStyle, { width: 48, margin: '0px', padding: '3px' }, 'editor dialog styles must not distort action buttons');
  assert.equal(await choices.first().locator('.sky-action-icon').evaluate(node => node.getBoundingClientRect().width), 40);
  assert.ok(await page.locator('.known-youtube .site-icon-brand').count() > 0, 'preview uses the current site brand');
  await page.evaluate(() => {
    const icon = SkyActions.renderIcon('https://synthetic-target.example/', SkyActions.resolve('simple-hug.png'), 'target');
    icon.id = 'target-brand'; document.body.append(icon);
  });
  await page.waitForFunction(() => document.querySelector('#target-brand .site-icon-brand')?.dataset.source === 'personal');
  await page.waitForFunction(() => document.querySelector('#target-brand .site-icon-brand-plate')?.dataset.tone === 'dark');
  await page.waitForFunction(() => document.querySelector('#target-brand .site-icon-person')?.dataset.personal === 'loaded');
  assert.match(await page.locator('#target-brand .site-icon-person').getAttribute('src'), /simple-hug\.png$/, 'target fallback branding must not replace the selected character');
  await page.locator('#target-brand').evaluate(node => node.remove());
  await choices.nth(1).click();
  assert.equal((await page.evaluate(() => window.selectedIds)).length, 1);
  const selected = await choices.nth(1).getAttribute('data-action');
  assert.equal(await choices.nth(1).getAttribute('aria-pressed'), 'true');
  await page.evaluate(() => window.picker.update({ site: { name: '工具', url: 'https://youtube.com/', group: 'tools' } }));
  assert.equal((await page.evaluate(() => window.selectedIds)).length, 1, 'updating category never selects automatically');
  assert.equal(await page.locator(`.sky-action-choice[data-action="${selected}"]`).first().getAttribute('aria-pressed'), 'true', 'manual selection remains selected');
  await page.locator('.sky-actions-toggle').click();
  assert.equal(await page.locator('.sky-actions-all .sky-action-choice').count(), 67, 'duplicate personal images appear once');
  assert.equal(await page.locator('.sky-actions-toggle').getAttribute('aria-expanded'), 'true');
  await page.waitForTimeout(300);
  assert.ok(personalRequests.size < 64, 'off-screen personal art should not all load when opening the catalog');
  await page.locator('.sky-actions-all .sky-action-choice').last().scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('.sky-actions-all .sky-action-choice:last-child .site-icon-person')?.src.includes('/personal/rk-test-63.png'));
  await page.locator('.sky-actions-all .sky-action-choice').last().click();
  const beforeScroll = await page.locator('.sky-actions-all').evaluate(node => node.scrollTop);
  assert.ok(beforeScroll > 0, 'the complete list is independently scrollable');
  await page.evaluate(() => window.picker.update({ selected: window.selectedIds.at(-1) }));
  assert.equal(await page.evaluate(() => document.activeElement?.dataset.action), 'rk-test-63.png', 're-render keeps keyboard focus on the chosen action');
  assert.equal(await page.locator('.sky-actions-all').evaluate(node => node.scrollTop), beforeScroll, 're-render keeps the catalog scroll position');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 320, height: 600 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.evaluate(() => window.picker.destroy());
  assert.equal(await choices.count(), 0);
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  console.log('PASS action picker: target brand, 40px, recommendations, expanded catalog, manual selection and responsive layout');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); server.close(); });
